#!/usr/bin/env python3
"""Lead only. After editing .github/team.json: invite everyone with a username and rewrite CODEOWNERS.

    python3 scripts/sync_team.py

Then commit .github/team.json and .github/CODEOWNERS through a pull request.
"""
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

with open(os.path.join(ROOT, ".github", "team.json")) as f:
    team = json.load(f)
repo, owner = team["repo"], team["repo"].split("/")[0].lower()

for m in team["members"]:
    u = m["github"]
    if not u:
        print(f"- {m['name']}: no username yet, skipped")
    elif u.lower() == owner:
        print(f"- {m['name']} (@{u}): owner")
    else:
        r = subprocess.run(["gh", "api", "-X", "PUT", f"repos/{repo}/collaborators/{u}", "-f", "permission=push"],
                           cwd=ROOT, capture_output=True, text=True)
        print(f"- {m['name']} (@{u}): " + ("invited (or already a member)" if r.returncode == 0 else "FAILED " + r.stderr.strip()))

leads = " ".join("@" + m["github"] for m in team["members"] if m["role"] == "lead" and m["github"])
with open(os.path.join(ROOT, ".github", "CODEOWNERS"), "w") as f:
    f.write("# Leads. Any of them can review a pull request into main and, once the review's findings are fixed, merge it.\n"
            "# Regenerated by scripts/sync_team.py from .github/team.json.\n"
            f"* {leads}\n")
print(f"CODEOWNERS now lists: {leads}")
